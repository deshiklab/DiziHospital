#!/usr/bin/env node
/**
 * DiziHospital design tokens — generator.
 *
 * Source of truth: docs/plan/design-tokens.json (versioned with the plan, reviewed like any other spec).
 * Outputs (packages/tokens/dist):
 *   tokens.css      CSS custom properties on :root
 *   theme.css       Tailwind v4 @theme block mapped to the same variables
 *   tokens.ts       typed TS object for use in components and tests
 *   tokens.json     flattened token list (name, value, comment) for tooling and audits
 *
 * Usage:
 *   node build.mjs            write the artefacts
 *   node build.mjs --check    verify the artefacts on disk match the source (CI drift gate)
 *
 * No dependencies: the generator is deliberately plain Node so it can never drift from the source
 * because of a tool update.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = process.env.TOKENS_SOURCE ?? join(here, '..', '..', 'docs', 'plan', 'design-tokens.json');
const outDir = join(here, 'dist');
const checkOnly = process.argv.includes('--check');

const raw = JSON.parse(readFileSync(source, 'utf8'));
const version = raw.meta?.version ?? '0.0.0';
const name = raw.meta?.name ?? 'DiziHospital design tokens';

/* ---------------------------------------------------------------- flatten */

/** Walk the nested token document and return a flat list of {path, value, comment}. */
function flatten(node, path = [], out = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const next = [...path, key];
    if (value && typeof value === 'object' && 'value' in value) {
      out.push({ path: next, value: value.value, comment: value.comment ?? null });
    } else if (value && typeof value === 'object') {
      flatten(value, next, out);
    }
  }
  return out;
}

const tokens = flatten(raw);
const cssName = (path) => '--dizi-' + path.map((p) => p.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()).join('-');

/* ------------------------------------------------------------------- emit */

function escapeCss(value) {
  const s = String(value);
  return /[;{}]/.test(s) ? JSON.stringify(s) : s;
}

function emitCss() {
  const lines = [
    `/* ${name} v${version} — GENERATED by packages/tokens/build.mjs. Do not edit. */`,
    `/* Source: docs/plan/design-tokens.json */`,
    ':root {',
  ];
  let group = null;
  for (const t of tokens) {
    if (t.path[0] !== group) {
      group = t.path[0];
      lines.push('');
      lines.push(`  /* ${group} */`);
    }
    lines.push(`  ${cssName(t.path)}: ${escapeCss(t.value)};${t.comment ? ` /* ${t.comment} */` : ''}`);
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitThemeCss() {
  const lines = [
    `/* ${name} v${version} — Tailwind v4 theme. GENERATED. */`,
    `/* Import after tokens.css:  @import "@dizi/tokens/css";  @import "@dizi/tokens/theme.css"; */`,
    '@theme {',
  ];
  for (const t of tokens) {
    // Tailwind namespaces: colours -> --color-*, fonts -> --font-*, spacing -> --spacing-*, others keep --dizi-*
    const [group, ...rest] = t.path;
    const tail = rest.map((p) => p.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()).join('-');
    let twName;
    if (group === 'color') twName = `--color-${tail}`;
    else if (group === 'typography' && rest[0] === 'family') twName = `--font-${tail}`;
    else if (group === 'space') twName = `--spacing-${tail}`;
    else if (group === 'radius') twName = `--radius-${tail}`;
    else twName = cssName(t.path);
    lines.push(`  ${twName}: var(${cssName(t.path)});`);
  }
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function emitTs() {
  const tree = {};
  for (const t of tokens) {
    let node = tree;
    for (const key of t.path.slice(0, -1)) node = node[key] ??= {};
    node[t.path.at(-1)] = t.value;
  }
  return [
    `/* ${name} v${version} — GENERATED. Do not edit. */`,
    `export const tokensVersion = ${JSON.stringify(version)};`,
    `export const tokens = ${JSON.stringify(tree, null, 2)} as const;`,
    `export type Tokens = typeof tokens;`,
    `export type TokenName = ${tokens.map((t) => JSON.stringify(t.path.join('.'))).join(' | ')};`,
    `/** CSS custom property name for a token path, e.g. cssVar('color.brand.500') -> var(--dizi-color-brand-500) */`,
    `export const cssVar = (path: TokenName): string => ({`,
    ...tokens.map((t) => `  ${JSON.stringify(t.path.join('.'))}: 'var(${cssName(t.path)})',`),
    `} as const)[path];`,
    '',
  ].join('\n');
}

function emitJson() {
  return JSON.stringify(
    {
      name,
      version,
      source: 'docs/plan/design-tokens.json',
      count: tokens.length,
      tokens: Object.fromEntries(tokens.map((t) => [t.path.join('.'), { css: cssName(t.path), value: t.value, comment: t.comment }])),
    },
    null,
    2,
  ) + '\n';
}

const artefacts = {
  'tokens.css': emitCss(),
  'theme.css': emitThemeCss(),
  'tokens.ts': emitTs(),
  'tokens.json': emitJson(),
};

/* ------------------------------------------------------------------ write */

if (checkOnly) {
  const drift = [];
  for (const [file, content] of Object.entries(artefacts)) {
    const target = join(outDir, file);
    if (!existsSync(target)) drift.push(`${file}: missing (run npm run tokens:build)`);
    else if (readFileSync(target, 'utf8') !== content) drift.push(`${file}: out of date with docs/plan/design-tokens.json`);
  }
  if (drift.length) {
    console.error('TOKEN DRIFT DETECTED\n' + drift.map((d) => '  - ' + d).join('\n'));
    process.exit(1);
  }
  console.log(`tokens up to date (${tokens.length} tokens, v${version})`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [file, content] of Object.entries(artefacts)) writeFileSync(join(outDir, file), content);
  console.log(`generated ${tokens.length} tokens (v${version}) into ${resolve(outDir)}`);
}
